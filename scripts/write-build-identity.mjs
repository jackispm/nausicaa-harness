import { createHash } from "node:crypto";
import { chmod, readFile, readdir, writeFile } from "node:fs/promises";
import { join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(process.argv[2] ?? fileURLToPath(new URL("../", import.meta.url)));
const output = join(root, "dist");
const identityPath = "runtime/build-identity.js";

async function runtimeFiles(directory, prefix = "") {
  const files = [];
  for (const entry of await readdir(directory, { withFileTypes: true })) {
    const path = `${prefix}${entry.name}`;
    if (entry.isDirectory()) {
      files.push(...await runtimeFiles(join(directory, entry.name), `${path}/`));
    } else if (entry.isFile() && path.endsWith(".js") && path !== identityPath) {
      files.push(path);
    }
  }
  return files.sort();
}

const hash = createHash("sha256");
for (const path of await runtimeFiles(output)) {
  hash.update(path).update("\0").update(await readFile(join(output, path))).update("\0");
}
// Lockfile and package metadata identify the dependencies shipped with this code.
for (const path of ["package.json", "package-lock.json"]) {
  try {
    hash.update(path).update("\0").update(await readFile(join(root, path))).update("\0");
  } catch (error) {
    if (path !== "package-lock.json" || error?.code !== "ENOENT") throw error;
  }
}
const runtimeBuildId = hash.digest("hex").slice(0, 12);
await writeFile(join(output, identityPath),
  `// Generated by the build pipeline; fixed when this module is loaded.\nexport const RUNTIME_BUILD_ID = ${JSON.stringify(runtimeBuildId)};\n`,
  "utf8");
await chmod(join(output, "cli.js"), 0o755);
console.log(`Runtime build: ${runtimeBuildId}`);
